// check:incident-report: the downloadable report, look and data
// ───────────────────────────────────────────────────────────────────
// Lucas, 2026-11-03: the report was "completely white, not branded in our
// UI", and it "dives deeper than the reports generated live", so every
// piece of data must flow into it correctly and never contradict the
// live views. This gate draws a full report from a test incident with
// src/incident_report_document.js and holds the data wiring in main.js.
// ═══════════════════════════════════════════════════════════════════
import { readFileSync } from 'node:fs';
import { NOT_RECORDED, renderIncidentReport, reportText } from '../src/incident_report_document.js';
import { REPORT_TOKENS } from '../src/report_theme.js';

let failures = 0;
const check = (label, ok, why) => {
  if (ok) { console.log(`  ok   ${label}`); return; }
  failures++; console.log(`  FAIL ${label}`); if (why) console.log(`       ${why}`);
};

const full = {
  id: 'DET-TEST-0001', generatedAt: '2026-11-03 12:00:00Z', type: 'Shahed-136 / Geran-2', platform: 'loitering-munition',
  classification: 'hostile', threat: 'high', confidence: '0.91', firstDetected: '09:00:02Z · DK Airport',
  identified: '09:00:10Z', closed: '09:03:05Z', duration: '03:03', status: 'CLOSED', outcome: 'NEUTRALIZED',
  exec: { text: 'Shahed-136 first detected — over DK Airport.', reco: 'Hold the cordon.', provenance: 'Generated by mistral-large' },
  analysis: { pattern: 'Low pass along the apron.', confidence: 'HIGH', dwell: [{ name: 'Apron East', pct: 47 }], flags: ['Sustained dwell'] },
  signals: { carrier: '1.6 GHz', bandwidth: '10 MHz', strongest: '-64 dBm at 09:01:10Z', loudest: '61 dB at 09:01:12Z', dominantHz: '180 Hz' },
  sitesCrossed: ['DK Airport', 'Amager Koblingsstation'], initialSite: 'DK Airport', lastConfirmed: 'Amager Koblingsstation', evasion: 'None',
  linkedEvents: [{ id: 'DET-TEST-0002', site: 'Amager Koblingsstation', status: 'closed' }], correlationScore: 88,
  sensors: [{ id: 'N27', site: 'DK Airport', node: 'Pier A', modalities: 'RF · Acoustic', coverage: '1000 m', status: 'ONLINE', peak: '0.94' }, { id: 'N99' }],
  timeline: [{ ts: '2026-11-03T09:00:02.000Z', kind: 'detected', text: 'First detected' }, { ts: '2026-11-03T09:01:00.000Z', kind: 'note', text: 'Ops: <script>alert(1)</script>' }],
  escalations: [{ sentAt: '2026-11-03T09:00:20.000Z', to: 'PET — Politiets Efterretningstjeneste', by: 'M. Sørensen (DK Airport)', status: 'acknowledged', ackAt: '2026-11-03T09:00:40.000Z', reply: { by: 'PET', text: 'Received' } }],
  response: { responder: 'Rigspolitiet interceptor', neutralisedAt: '09:02:30Z', position: '55.6181°N 12.6561°E', zone: 'DK Airport', kills: 1, outcome: 'NEUTRALIZED' },
  wreckages: [{ at: '2026-11-03T09:02:30.000Z', position: '55.6181°N 12.6561°E', mode: 'fell to ground', by: 'Rigspolitiet interceptor' }],
  dispatches: [{ asset: 'Rigspolitiet interceptor', agency: 'Rigspolitiet', kind: 'counter drone swarm', sentAt: '2026-11-03T09:01:10.000Z', outcome: 'Neutralised', distance: '4 km' }],
  postIncident: [{ handoff: 'Verá command layer', status: 'PENDING' }],
};
const html = renderIncidentReport(full, { logoUrl: 'data:image/png;base64,AAAA' });

console.log('\n[every section draws]');
for (const title of ['Executive Summary', 'Track Metadata', 'Analysis', 'Detection Evidence', 'Sensor Path (Cross Cueing)', 'Contributing Sensors',
  'Timeline', 'Escalation Log', 'Response Action', 'Wreckage', 'Dispatched Counter-Drone Assets', 'Post Incident Dispatch']) {
  check(title, html.includes(`<h2>${title}</h2>`));
}
check('a missile report shows air defence instead of counter-drone assets',
  renderIncidentReport({ ...full, airDefense: [{ name: 'Skrydstrup', operator: 'Flyvevåbnet', role: 'F-35 QRA', distance: '210 km', status: 'AVAILABLE' }] }, {}).includes('<h2>Available Air Defense Assets</h2>'));
check('the deeper data is there: linked events, replies, acknowledgements, wreckage, dispatch agency',
  html.includes('DET-TEST-0002') && html.includes('PET: Received') && html.includes('09:00:40Z') && html.includes('fell to ground') && html.includes('>Rigspolitiet<'));

console.log('\n[the platform\'s rules]');
check('no em or en dash survives, even from account names and model text', !/[—–]/.test(html));
check('text is escaped', !html.includes('<script>alert(1)</script>') && html.includes('&lt;script&gt;'));
check('a missing value reads "Not recorded"', (html.match(/Not recorded/g) || []).length >= 3 && NOT_RECORDED === 'Not recorded');
check('reportText turns a dash into a comma', reportText('A — B') === 'A, B');
check('drawn in the platform\'s tokens, not the old white page',
  html.includes('--surface-bg') && html.includes('--font-mono') && !/Courier New|#f5f5f5|#f9f9f9|color: #111/.test(html)
  && Object.keys(REPORT_TOKENS).every((k) => html.includes(k)));
check('the real logo sits in the bar and the footer', (html.match(/data:image\/png;base64,AAAA/g) || []).length === 2);
check('an empty incident still draws, without throwing', /Not recorded/.test(renderIncidentReport({}, {})));

console.log('\n[main.js feeds it from the live views\' sources]');
const main = readFileSync(new URL('../src/main.js', import.meta.url), 'utf8');
const s = main.indexOf('function generatePirReport(');
const fn = main.slice(s, main.indexOf("toast('Incident report generated.", s));
check('the report is drawn by incident_report_document.js', /renderIncidentReport\(model, \{ doc: document, logoUrl: _logoUrl \}\)/.test(fn) && !/<!DOCTYPE html>/.test(fn));
check('sensors are looked up in the incident\'s own sites, in order', /for \(const siteId of _sitesInOrder\)/.test(fn) && !/for \(const site of Object\.values\(SITES\)\)/.test(fn));
check('escalation times come from the status history, recipients by name',
  /esc\.statusHistory\?\.\[0\]\?\.timestamp/.test(fn) && /getDestination\(id\)\?\.name \|\| id/.test(fn) && !/esc\.timestamp/.test(fn));
check('acknowledgements and replies are read from the record', /h\.status === 'acknowledged'/.test(fn) && /esc\.responses/.test(fn));
check('summary, responder and analysis come from the same helpers as the panel, the carrier from the recording\'s own',
  /incidentExecSummary\(e, \{/.test(fn) && /responder: respondersOf\(e\)/.test(fn) && /_generateAgentBNarrative\(e\)/.test(fn) && /signatureFieldsFromEvidence\(e\.evidence\)/.test(fn));
check('only the signals that dominate a case: no visual match and no signature match, which have no traceable input (Lucas, 2026-11-06)',
  !/Signature match|Visual match|Radio Frequency/.test(html) && !/rfMatch|visual_match/.test(fn)
  && html.includes('Strongest radiofrequency signal') && html.includes('Loudest acoustic level'));
const swarmHtml = renderIncidentReport({ ...full, signals: null, formation: [{ anchor: 'drone-4', label: 'DRONE-4', observed: true,
  signals: { carrier: '5780 MHz', strongest: '-74 dBm at 09:01:00Z' }, topSensors: [], history: [] }] }, {});
check('a formation\'s detection evidence is per drone, with each drone\'s own carrier',
  swarmHtml.includes('Each drone\'s detection evidence is in its own section below.') && swarmHtml.includes('5780 MHz') && !swarmHtml.includes('1.6 GHz'));
check('one dispatch row per dispatch, not per airframe', /d\.groupId \|\| d\.dispatchId/.test(fn));
check('the logo is embedded', /reportLogoUrl\(document\)/.test(fn));
check('no em dash anywhere in the report builder', !/[—]/.test(fn));

console.log(failures ? `\n${failures} failing` : '\nall passing');
process.exit(failures ? 1 : 0);
